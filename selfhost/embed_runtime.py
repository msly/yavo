#!/usr/bin/env python3
"""Reproduce the standalone selfhost driver's embedded runtime and lock version."""
from __future__ import annotations

import argparse
import hashlib
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
HEADER = ROOT / "compiler" / "runtime" / "yavo_rt.h"
LOCK = ROOT / "compiler" / "toolchain.lock"
OUTPUT = ROOT / "selfhost" / "runtime_source.yv"


def literal(value: str) -> str:
    if any(ord(c) < 32 and c not in "\n\r\t" for c in value):
        raise ValueError("runtime contains an unsupported literal control byte")
    value = value.replace("\\", "\\\\").replace('"', '\\"')
    value = value.replace("\n", "\\n").replace("\r", "\\r").replace("\t", "\\t")
    value = value.replace("$" + "{", "\\" + "$" + "{")
    return '"' + value + '"'


def render() -> bytes:
    raw = HEADER.read_bytes()
    header = raw.decode("utf-8")
    versions = [line.split("=", 1)[1].strip()
                for line in LOCK.read_text(encoding="utf-8").splitlines()
                if line.split("=", 1)[0].strip() == "zig_version"]
    if len(versions) != 1 or not versions[0]:
        raise ValueError("toolchain.lock must have exactly one zig_version")
    lines = [
        "// Generated by selfhost/embed_runtime.py; do not edit by hand.",
        "// Runtime SHA256: " + hashlib.sha256(raw).hexdigest(),
        "// The driver can build from any working directory without a source checkout.",
        "",
        "pub fn version() -> str of static { return " + literal(versions[0]) + " }",
        "",
        "pub fn header() -> String {",
        "    var output = String{}",
    ]
    for start in range(0, len(header), 2048):
        lines.append("    output.push(" + literal(header[start:start + 2048]) + ")")
    lines.extend(["    return output", "}", ""])
    return "\n".join(lines).encode("utf-8")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true",
                        help="fail if the checked-in embedding does not match the runtime and lock")
    options = parser.parse_args()
    expected = render()
    if options.check:
        if not OUTPUT.is_file() or OUTPUT.read_bytes() != expected:
            print("selfhost/runtime_source.yv is stale; run selfhost/embed_runtime.py", file=sys.stderr)
            return 1
        print("embedded runtime and locked version match")
        return 0
    OUTPUT.write_bytes(expected)
    print("wrote selfhost/runtime_source.yv")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
