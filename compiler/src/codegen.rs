/// Drop and clone of a struct (fields dropped in reverse declaration order, V10) or an enum
/// (only the current case's payload).
fn agg_helpers(out: &mut String, s: &HStruct) {
    let (key, c) = (s.ty.key(), s.ty.c_name());
    let mut drops = String::new();
    let mut clones = String::new();
    match s.ty {
        Ty::Struct(_) => {
            for (n, t) in s.fields.iter().rev().filter(|(_, t)| t.needs_drop()) {
                let _ = write!(drops, "\n    {}(&p->f_{n});", drop_fn(*t));
            }
            for (n, t) in s.fields.iter().filter(|(_, t)| t.needs_drop()) {
                let _ = write!(clones, "\n    o.f_{n} = {};", clone_value(*t, &format!("p->f_{n}")));
            }
        }
        _ => {
            drops.push_str("\n    switch (p->tag) {");
            clones.push_str("\n    switch (p->tag) {");
            for (vi, (_, fields)) in s.variants.iter().enumerate() {
                if !fields.iter().any(|(_, t)| t.needs_drop()) {
                    continue;
                }
                let _ = write!(drops, "\n    case {vi}:");
                for (n, t) in fields.iter().rev().filter(|(_, t)| t.needs_drop()) {
                    let _ = write!(drops, " {}(&p->u.v{vi}.f_{n});", drop_fn(*t));
                }
                drops.push_str(" break;");
                let _ = write!(clones, "\n    case {vi}:");
                for (n, t) in fields.iter().filter(|(_, t)| t.needs_drop()) {
                    let _ = write!(clones, " o.u.v{vi}.f_{n} = {};", clone_value(*t, &format!("p->u.v{vi}.f_{n}")));
                }
                clones.push_str(" break;");
            }
            drops.push_str("\n    default: break;\n    }");
            clones.push_str("\n    default: break;\n    }");
        }
    }
    if has_user_drop(s.ty) {
        // The user's drop runs on a complete, live value, then the fields are dropped (V10).
        // A moved-out value is all zero, so `yv_live` is 0 and nothing runs.
        let user = format!("yv_fn_{}__drop", s.ty);
        let _ = writeln!(out, "static void {user}({c} *self);");
        drops = format!("\n    if (!p->yv_live) return;\n    p->yv_live = 0;\n    {user}(p);{drops}");
    }
    let _ = writeln!(out, "static inline void yv_drop_{key}({c} *p) {{{drops}\n}}");
    let _ = writeln!(
        out,
        "static inline {c} yv_clone_{key}(const {c} *p, uint32_t line, uint32_t col) {{\n    {c} o = *p;{clones}\n    (void)line; (void)col;\n    return o;\n}}\n"
    );
}

/// Writes one value of `${...}` to the output target `o` (a `const yv_out *`); `None` for types
/// that have no printed form (shown as `..` inside an enum's payload).
fn value_writer(o: &str, t: Ty, v: &str) -> Option<String> {
    Some(match t {
        Ty::Int(i) if i.signed() => format!("yv_out_i64({o}, (int64_t){v});"),
        Ty::Int(_) => format!("yv_out_u64({o}, (uint64_t){v});"),
        Ty::Float(f) => format!("yv_out_{}({o}, {v});", f.name()),
        Ty::Bool => format!("yv_out_bool({o}, {v});"),
        Ty::Str => format!("yv_out_str({o}, {v});"),
        Ty::String => format!("yv_out_str({o}, yv_string_view(&{v}));"),
        Ty::Enum(_) => format!("yv_print_{}({o}, &{v});", t.key()),
        _ => return None,
    })
}

/// `Name` for a case without payload, `Name(field: value, ...)` otherwise.
fn enum_printer(out: &mut String, e: &HStruct) {
    let (key, c) = (e.ty.key(), e.ty.c_name());
    let _ = writeln!(out, "static void yv_print_{key}(const yv_out *o, const {c} *p) {{\n    switch (p->tag) {{");
    for (vi, (name, fields)) in e.variants.iter().enumerate() {
        let _ = write!(out, "    case {vi}:\n        yv_out_bytes(o, {}, {});", c_string(name.as_bytes()), name.len());
        if !fields.is_empty() {
            out.push_str("\n        yv_out_bytes(o, \"(\", 1);");
            for (i, (fname, t)) in fields.iter().enumerate() {
                let label = format!("{}{fname}: ", if i > 0 { ", " } else { "" });
                let _ = write!(out, "\n        yv_out_bytes(o, {}, {});", c_string(label.as_bytes()), label.len());
                let w = value_writer("o", *t, &format!("p->u.v{vi}.f_{fname}")).unwrap_or_else(|| "yv_out_bytes(o, \"..\", 2);".into());
                let _ = write!(out, "\n        {w}");
            }
            out.push_str("\n        yv_out_bytes(o, \")\", 1);");
        }
        out.push_str("\n        break;\n");
    }
    out.push_str("    default:\n        break;\n    }\n}\n\n");
}

