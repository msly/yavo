//! Lowers the typed IR to C17. Every sub-expression is evaluated into a temporary in
//! source order, so Yavo's left-to-right evaluation does not depend on C's unspecified
//! argument order. Checked arithmetic calls into `yavo_rt.h`.

use std::fmt::Write;

use crate::ast::BinOp;
use crate::check::*;
use crate::diag::Span;
use crate::types::{all_vecs, vec_elem, IntTy, Ty};

pub const RUNTIME_HEADER: &str = include_str!("../runtime/yavo_rt.h");

pub fn generate(prog: &HProgram, file: &str) -> String {
    let mut g = Gen {
        out: String::new(),
        indent: 0,
        tmp: 0,
        fn_names: Vec::new(),
        fn_sinks: prog.fns.iter().map(|f| f.sinks.clone()).collect(),
        fields: Default::default(),
        scopes: Vec::new(),
        temps: Vec::new(),
    };
    g.fn_names = prog.fns.iter().map(|f| format!("yv_fn_{}", f.name)).collect();
    let _ = writeln!(g.out, "/* Generated by yavo {} from {} -- do not edit. */", env!("CARGO_PKG_VERSION"), file);
    g.out.push_str("#include \"yavo_rt.h\"\n\n");
    let _ = writeln!(g.out, "static const char yv_source_file[] = {};\n", c_string(file.as_bytes()));
    // Structs come in dependency order, so every field type is complete where it is used.
    for s in &prog.structs {
        let Ty::Struct(id) = s.ty else { unreachable!() };
        let c = s.ty.c_name();
        let _ = writeln!(g.out, "typedef struct {c} {{");
        if s.fields.is_empty() {
            g.out.push_str("    char yv_empty;\n");
        }
        for (name, ty) in &s.fields {
            let _ = writeln!(g.out, "    {} f_{name};", ty.c_name());
        }
        let _ = writeln!(g.out, "}} {c};\n");
        g.fields.insert(id, s.fields.clone());
    }
    // Drop and clone helpers for owned types; vectors are registered inner types first.
    g.out.push_str("static inline void yv_drop_String(yv_string *p) { yv_string_drop(p); }\n");
    g.out.push_str(
        "static inline yv_string yv_clone_String(const yv_string *p, uint32_t line, uint32_t col) {\n    \
         return yv_string_from(yv_string_view(p), line, col);\n}\n",
    );
    for (id, elem) in all_vecs() {
        let key = Ty::Vec(id).key();
        let et = elem.c_name();
        let _ = writeln!(g.out, "static inline void yv_drop_{key}(yv_vec *p) {{");
        if !elem.is_copy() {
            let _ = writeln!(g.out, "    for (int64_t i = 0; i < p->len; i++) {}(&(({et} *)p->ptr)[i]);", drop_fn(elem));
        }
        let _ = writeln!(g.out, "    yv_vec_free(p);\n}}");
        let _ = writeln!(g.out, "static inline yv_vec yv_clone_{key}(const yv_vec *p, uint32_t line, uint32_t col) {{");
        let _ = writeln!(g.out, "    yv_vec v = yv_vec_with_cap((int64_t)sizeof({et}), p->len, line, col);");
        if elem.is_copy() {
            let _ = writeln!(g.out, "    if (p->len) memcpy(v.ptr, p->ptr, (size_t)p->len * sizeof({et}));");
            let _ = writeln!(g.out, "    v.len = p->len;");
        } else {
            let _ = writeln!(
                g.out,
                "    for (int64_t i = 0; i < p->len; i++) {{\n        (({et} *)v.ptr)[i] = {}(&((const {et} *)p->ptr)[i], line, col);\n        v.len = i + 1;\n    }}",
                clone_fn(elem)
            );
        }
        let _ = writeln!(g.out, "    return v;\n}}\n");
    }
    for f in &prog.fns {
        let sig = g.signature(f);
        let _ = writeln!(g.out, "static {sig};");
    }
    g.out.push('\n');
    for f in &prog.fns {
        g.function(f);
    }
    let main = prog.fns.iter().position(|f| f.name == "main").expect("checked: main exists");
    let _ = writeln!(
        g.out,
        "int main(void) {{\n    yv_rt_init(yv_source_file);\n    {}();\n    return yv_rt_exit();\n}}",
        g.fn_names[main]
    );
    g.out
}

struct Gen {
    out: String,
    indent: usize,
    tmp: usize,
    fn_names: Vec<String>,
    /// `fn_sinks[f][i]`: parameter `i` of function `f` takes ownership of its argument.
    fn_sinks: Vec<Vec<bool>>,
    /// Field names and types of each struct, by struct id.
    fields: std::collections::HashMap<u32, Vec<(String, Ty)>>,
    /// Open scopes, innermost last, with the owned locals declared in each so far.
    scopes: Vec<Scope>,
    /// Owned temporaries of the current statement that were only borrowed.
    temps: Vec<(String, Ty)>,
}

struct Scope {
    owned: Vec<(String, Ty)>,
    /// The body of a loop: `break`/`continue` leave every scope up to and including this one.
    is_loop: bool,
}

fn drop_fn(ty: Ty) -> String {
    format!("yv_drop_{}", ty.key())
}

/// `(a == b)` -> `a == b`, so that `if (...)` does not trigger clang's `-Wparentheses-equality`.
fn strip_parens(c: &str) -> &str {
    let bytes = c.as_bytes();
    if bytes.first() != Some(&b'(') || bytes.last() != Some(&b')') {
        return c;
    }
    let mut depth = 0i32;
    let (mut in_str, mut escaped) = (false, false);
    for (i, &b) in bytes.iter().enumerate() {
        if in_str {
            match (escaped, b) {
                (true, _) => escaped = false,
                (false, b'\\') => escaped = true,
                (false, b'"') => in_str = false,
                _ => {}
            }
            continue;
        }
        match b {
            b'"' => in_str = true,
            b'(' => depth += 1,
            b')' => depth -= 1,
            _ => {}
        }
        if depth == 0 && i + 1 < bytes.len() {
            return c; // the first `(` closes before the end: not one enclosing group
        }
    }
    &c[1..c.len() - 1]
}

fn clone_fn(ty: Ty) -> String {
    format!("yv_clone_{}", ty.key())
}

fn local_name(locals: &[HLocal], id: LocalId) -> String {
    // An `inout` parameter is a pointer to the caller's place.
    if locals[id].inout {
        format!("(*{})", raw_local_name(locals, id))
    } else {
        raw_local_name(locals, id)
    }
}

/// The C variable itself (hidden locals are named `$iter<n>`; `$` is not valid in C).
fn raw_local_name(locals: &[HLocal], id: LocalId) -> String {
    format!("l{}_{}", id, locals[id].name.replace('$', "h_"))
}

fn c_string(bytes: &[u8]) -> String {
    let mut s = String::from("\"");
    for &b in bytes {
        match b {
            b'"' => s.push_str("\\\""),
            b'\\' => s.push_str("\\\\"),
            b'?' => s.push_str("\\?"),
            b'\n' => s.push_str("\\n"),
            b'\t' => s.push_str("\\t"),
            0x20..=0x7e => s.push(b as char),
            _ => {
                let _ = write!(s, "\\{b:03o}");
            }
        }
    }
    s.push('"');
    s
}

fn int_literal(v: i128, t: IntTy) -> String {
    if t.signed() {
        if v == i64::MIN as i128 {
            "INT64_MIN".to_string()
        } else {
            format!("(({})INT64_C({v}))", t.c_name())
        }
    } else {
        format!("(({})UINT64_C({v}))", t.c_name())
    }
}

fn pos(span: Span) -> String {
    format!("{}, {}", span.line, span.col)
}

impl Gen {
    fn line(&mut self, text: &str) {
        for _ in 0..self.indent {
            self.out.push_str("    ");
        }
        self.out.push_str(text);
        self.out.push('\n');
    }

    fn fresh(&mut self) -> String {
        self.tmp += 1;
        format!("t{}", self.tmp)
    }

    fn signature(&self, f: &HFn) -> String {
        let idx = self.fn_names.iter().position(|n| *n == format!("yv_fn_{}", f.name)).unwrap();
        let params: Vec<String> = f
            .params
            .iter()
            .map(|&id| {
                let ptr = if f.locals[id].inout { "*" } else { "" };
                format!("{} {ptr}{}", f.locals[id].ty.c_name(), raw_local_name(&f.locals, id))
            })
            .collect();
        let params = if params.is_empty() { "void".to_string() } else { params.join(", ") };
        format!("{} {}({})", f.ret.c_name(), self.fn_names[idx], params)
    }

    fn function(&mut self, f: &HFn) {
        self.tmp = 0;
        let sig = self.signature(f);
        self.line(&format!("static {sig} {{"));
        self.indent += 1;
        // `sink` parameters are owned by the function; borrowed parameters belong to the caller.
        let owned_params: Vec<(String, Ty)> = f
            .params
            .iter()
            .filter(|&&id| f.locals[id].owned)
            .map(|&id| (local_name(&f.locals, id), f.locals[id].ty))
            .collect();
        self.scopes.push(Scope { owned: owned_params, is_loop: false });
        self.stmts(&f.body, f);
        self.close_scope();
        if f.ret != Ty::Unit {
            // Unreachable: the checker proved every path returns.
            self.line("YV_UNREACHABLE();");
        }
        self.indent -= 1;
        self.line("}\n");
    }

    fn stmts(&mut self, stmts: &[HStmt], f: &HFn) {
        for s in stmts {
            self.stmt(s, f);
            // Owned temporaries that were only borrowed die at the end of their statement.
            self.flush_temps();
        }
    }

    /// Statements in their own scope; the owned locals declared there are dropped at its end.
    fn scoped(&mut self, stmts: &[HStmt], f: &HFn, is_loop: bool) {
        self.scopes.push(Scope { owned: Vec::new(), is_loop });
        self.stmts(stmts, f);
        self.close_scope();
    }

    fn block(&mut self, stmts: &[HStmt], f: &HFn, is_loop: bool) {
        self.indent += 1;
        self.scoped(stmts, f, is_loop);
        self.indent -= 1;
    }

    fn close_scope(&mut self) {
        let scope = self.scopes.pop().expect("an open scope");
        for (name, ty) in scope.owned.iter().rev() {
            self.line(&format!("{}(&{name});", drop_fn(*ty)));
        }
    }

    /// Drops the owned locals of the innermost `n` scopes (innermost first) before a jump.
    /// Moved-out locals are empty, so dropping them does nothing.
    fn drop_scopes(&mut self, n: usize) {
        let drops: Vec<String> = self
            .scopes
            .iter()
            .rev()
            .take(n)
            .flat_map(|s| s.owned.iter().rev())
            .map(|(name, ty)| format!("{}(&{name});", drop_fn(*ty)))
            .collect();
        for d in drops {
            self.line(&d);
        }
    }

    /// Number of scopes from the innermost one up to and including the innermost loop body.
    fn scopes_to_loop(&self) -> usize {
        self.scopes.iter().rev().position(|s| s.is_loop).map(|p| p + 1).unwrap_or(0)
    }

    fn flush_temps(&mut self) {
        let temps = std::mem::take(&mut self.temps);
        for (name, ty) in temps.iter().rev() {
            self.line(&format!("{}(&{name});", drop_fn(*ty)));
        }
    }

    /// A condition value that stays valid after the statement's temporaries are dropped.
    fn settle_cond(&mut self, c: String) -> String {
        if self.temps.is_empty() {
            return c;
        }
        let t = self.bind(Ty::Bool, &c);
        self.flush_temps();
        t
    }

    fn stmt(&mut self, s: &HStmt, f: &HFn) {
        match &s.kind {
            HStmtKind::Let { local, init } => {
                let v = self.owned(init, f);
                let ty = f.locals[*local].ty;
                let name = local_name(&f.locals, *local);
                self.line(&format!("{} {name} = {v};", ty.c_name()));
                if f.locals[*local].owned {
                    self.scopes.last_mut().expect("an open scope").owned.push((name, ty));
                }
            }
            HStmtKind::Assign { local, path, value } => {
                let v = self.owned(value, f);
                let mut place = local_name(&f.locals, *local);
                let mut ty = f.locals[*local].ty;
                for &fi in path {
                    let Ty::Struct(id) = ty else { unreachable!() };
                    let (name, fty) = &self.fields[&id][fi];
                    place = format!("{place}.f_{name}");
                    ty = *fty;
                }
                if !ty.is_copy() {
                    // The new value is computed first; then the old one is dropped and replaced.
                    self.line(&format!("{}(&{place});", drop_fn(ty)));
                }
                self.line(&format!("{place} = {v};"));
            }
            HStmtKind::Discard(e) => {
                // `let _ = x` leaves a variable alone; any other value is dropped right away.
                if !matches!(e.kind, HExprKind::Local(_)) {
                    let v = self.borrowed(e, f);
                    if e.ty != Ty::Unit {
                        self.line(&format!("(void){v};"));
                    }
                }
            }
            HStmtKind::Expr(e) => {
                let v = self.borrowed(e, f);
                if e.ty != Ty::Unit {
                    self.line(&format!("(void){v};"));
                }
            }
            HStmtKind::If { cond, then, els } => {
                let c = self.expr(cond, f);
                let c = self.settle_cond(c);
                self.line(&format!("if ({}) {{", strip_parens(&c)));
                self.block(then, f, false);
                if els.is_empty() {
                    self.line("}");
                } else {
                    self.line("} else {");
                    self.block(els, f, false);
                    self.line("}");
                }
            }
            HStmtKind::While { cond, body } => {
                self.line("for (;;) {");
                self.indent += 1;
                let c = self.expr(cond, f);
                let c = self.settle_cond(c);
                self.line(&format!("if (!({})) break;", strip_parens(&c)));
                self.scoped(body, f, true);
                self.indent -= 1;
                self.line("}");
            }
            HStmtKind::Loop { body } => {
                self.line("for (;;) {");
                self.block(body, f, true);
                self.line("}");
            }
            HStmtKind::For { local, start, end, body } => {
                let ty = f.locals[*local].ty.c_name();
                let a = self.expr(start, f);
                let b = self.expr(end, f);
                let end_tmp = self.fresh();
                let name = local_name(&f.locals, *local);
                self.line("{");
                self.indent += 1;
                self.line(&format!("const {ty} {end_tmp} = {b};"));
                // `i < end` guarantees `i + 1` cannot overflow.
                self.line(&format!("for ({ty} {name} = {a}; {name} < {end_tmp}; {name}++) {{"));
                self.block(body, f, true);
                self.line("}");
                self.indent -= 1;
                self.line("}");
            }
            HStmtKind::Break | HStmtKind::Continue => {
                let n = self.scopes_to_loop();
                self.drop_scopes(n);
                self.line(if matches!(s.kind, HStmtKind::Break) { "break;" } else { "continue;" });
            }
            HStmtKind::ForEach { vec, elem, by_ref, body } => {
                let v = local_name(&f.locals, *vec);
                let Ty::Vec(vid) = f.locals[*vec].ty else { unreachable!() };
                let ec = vec_elem(vid).c_name();
                let i = self.fresh();
                let x = local_name(&f.locals, *elem);
                // The checker forbids changing `v` during the loop, so `len` and `ptr` stay valid.
                self.line(&format!("for (int64_t {i} = 0; {i} < ({v}).len; {i}++) {{"));
                self.indent += 1;
                if *by_ref {
                    self.line(&format!("const {ec} *{x} = &(({ec} *)({v}).ptr)[{i}];"));
                } else {
                    self.line(&format!("{ec} {x} = (({ec} *)({v}).ptr)[{i}];"));
                }
                self.scoped(body, f, true);
                self.indent -= 1;
                self.line("}");
            }
            HStmtKind::Return(value) => {
                let v = value.as_ref().map(|e| {
                    let v = self.owned(e, f);
                    self.bind(e.ty, &v)
                });
                self.flush_temps();
                let n = self.scopes.len();
                self.drop_scopes(n);
                match v {
                    Some(v) => self.line(&format!("return {v};")),
                    None => self.line("return;"),
                }
            }
            HStmtKind::Print { fd, newline, parts } => {
                // Evaluate all interpolation operands in source order before any
                // outer output. Store values, not a heap-allocated formatted string.
                // A failing operand must not leave an already-written outer prefix.
                let mut writes = Vec::new();
                for part in parts {
                    match part {
                        PrintPart::Text(t) => {
                            if !t.is_empty() {
                                let lit = c_string(t.as_bytes());
                                writes.push(format!("yv_write({fd}, {lit}, {});", t.len()));
                            }
                        }
                        PrintPart::Value(e) => {
                            let v = self.borrowed(e, f);
                            let v = self.bind(e.ty, &v);
                            let call = match e.ty {
                                Ty::Int(t) if t.signed() => format!("yv_write_i64({fd}, (int64_t){v});"),
                                Ty::Int(_) => format!("yv_write_u64({fd}, (uint64_t){v});"),
                                Ty::Bool => format!("yv_write_bool({fd}, {v});"),
                                Ty::Str => format!("yv_write_str({fd}, {v});"),
                                Ty::String => format!("yv_write_str({fd}, yv_string_view(&{v}));"),
                                Ty::Unit | Ty::Error | Ty::Struct(_) | Ty::Vec(_) | Ty::Ref(_) => {
                                    unreachable!("rejected or dereferenced by the checker")
                                }
                            };
                            writes.push(call);
                        }
                    }
                }
                self.line(&format!("yv_output_at({});", pos(s.span)));
                for write in writes {
                    self.line(&write);
                }
                if *newline {
                    self.line(&format!("yv_write({fd}, \"\\n\", 1);"));
                }
            }
            HStmtKind::Block(b) => {
                self.line("{");
                self.block(b, f, false);
                self.line("}");
            }
        }
    }

    /// Emits the statements that compute `e` and returns a C expression naming its value.
    fn expr(&mut self, e: &HExpr, f: &HFn) -> String {
        match &e.kind {
            HExprKind::Int(v) => match e.ty {
                Ty::Int(t) => int_literal(*v, t),
                _ => unreachable!(),
            },
            HExprKind::Bool(b) => b.to_string(),
            HExprKind::Str(s) => format!("((yv_str){{{}, {}}})", c_string(s.as_bytes()), s.len()),
            HExprKind::Local(id) => local_name(&f.locals, *id),
            HExprKind::Error => unreachable!("codegen only runs on error-free programs"),
            HExprKind::StructLit { fields } => {
                // Field values are bound to temporaries in the order written, so the C
                // initializer (whose evaluation order is unspecified) only copies values.
                let Ty::Struct(id) = e.ty else { unreachable!() };
                let mut inits = Vec::new();
                for (fi, fe) in fields {
                    let v = self.expr(fe, f);
                    let v = self.bind(fe.ty, &v);
                    inits.push(format!(".f_{} = {v}", self.fields[&id][*fi].0));
                }
                let body = if inits.is_empty() { "0".to_string() } else { inits.join(", ") };
                self.bind(e.ty, &format!("(({}){{{body}}})", e.ty.c_name()))
            }
            HExprKind::Field { base, field } => {
                let Ty::Struct(id) = base.ty else { unreachable!() };
                let b = self.expr(base, f);
                format!("({b}).f_{}", self.fields[&id][*field].0)
            }
            HExprKind::Call { func, args } => {
                // A `sink` argument is handed over; any other owned argument is borrowed and,
                // if it is a temporary, dropped at the end of the statement.
                let sinks = self.fn_sinks[*func].clone();
                let vals: Vec<String> = args
                    .iter()
                    .enumerate()
                    .map(|(i, a)| {
                        if sinks.get(i).copied().unwrap_or(false) || a.ty.is_copy() {
                            self.owned(a, f)
                        } else {
                            self.borrowed(a, f)
                        }
                    })
                    .collect();
                let call = format!("{}({})", self.fn_names[*func], vals.join(", "));
                if e.ty == Ty::Unit {
                    self.line(&format!("{call};"));
                    String::new()
                } else if e.ty.is_copy() {
                    self.bind(e.ty, &call)
                } else {
                    self.bind_mut(e.ty, &call)
                }
            }
            HExprKind::Move(id) => {
                let name = local_name(&f.locals, *id);
                let t = self.bind_mut(e.ty, &name);
                self.line(&format!("{name} = ({}){{0}};", e.ty.c_name()));
                t
            }
            HExprKind::VecLit(items) => {
                let Ty::Vec(vid) = e.ty else { unreachable!() };
                let et = vec_elem(vid).c_name();
                let at = pos(e.at);
                let t = self.fresh();
                self.line(&format!("yv_vec {t} = yv_vec_with_cap((int64_t)sizeof({et}), {}, {at});", items.len()));
                for it in items {
                    let v = self.owned(it, f);
                    self.line(&format!("*({et} *)yv_vec_push_slot(&{t}, (int64_t)sizeof({et}), {at}) = {v};"));
                }
                t
            }
            HExprKind::Index { base, index } => {
                let b = self.borrowed(base, f);
                let i = self.expr(index, f);
                let at = pos(e.at);
                let text = match base.ty {
                    // A non-copyable element is read in place: the value is a pointer into `v`.
                    Ty::Vec(vid) if matches!(e.ty, Ty::Ref(_)) => {
                        let et = vec_elem(vid).c_name();
                        format!("(({et} *)yv_vec_at(&{b}, (int64_t)sizeof({et}), (int64_t){i}, {at}))")
                    }
                    Ty::Vec(vid) => {
                        let et = vec_elem(vid).c_name();
                        format!("(*({et} *)yv_vec_at(&{b}, (int64_t)sizeof({et}), (int64_t){i}, {at}))")
                    }
                    Ty::Str => format!("yv_str_at({b}, (int64_t){i}, {at})"),
                    Ty::String => format!("yv_str_at(yv_string_view(&{b}), (int64_t){i}, {at})"),
                    _ => unreachable!(),
                };
                self.bind(e.ty, &text)
            }
            HExprKind::Method { method, recv } => {
                let at = pos(e.at);
                match method {
                    Builtin::StrToString => {
                        let s = self.expr(recv, f);
                        self.bind_mut(e.ty, &format!("yv_string_from({s}, {at})"))
                    }
                    Builtin::StrLen => {
                        let s = self.expr(recv, f);
                        self.bind(e.ty, &format!("(int64_t)({s}).len"))
                    }
                    Builtin::StringLen | Builtin::VecLen => {
                        let s = self.borrowed(recv, f);
                        self.bind(e.ty, &format!("({s}).len"))
                    }
                    Builtin::StringClone | Builtin::VecClone => {
                        let s = self.borrowed(recv, f);
                        self.bind_mut(e.ty, &format!("{}(&{s}, {at})", clone_fn(recv.ty)))
                    }
                    Builtin::Trim | Builtin::Fields | Builtin::Lines => {
                        let view = if recv.ty == Ty::String {
                            let s = self.borrowed(recv, f);
                            format!("yv_string_view(&{s})")
                        } else {
                            self.expr(recv, f)
                        };
                        match method {
                            Builtin::Trim => self.bind(e.ty, &format!("yv_str_trim({view})")),
                            Builtin::Fields => self.bind_mut(e.ty, &format!("yv_str_fields({view}, {at})")),
                            _ => self.bind_mut(e.ty, &format!("yv_str_lines({view}, {at})")),
                        }
                    }
                }
            }
            HExprKind::StrView(inner) => {
                let s = self.borrowed(inner, f);
                self.bind(e.ty, &format!("yv_string_view(&{s})"))
            }
            HExprKind::Deref(inner) => {
                let p = self.expr(inner, f);
                format!("(*{p})")
            }
            HExprKind::InoutArg(id) => {
                if f.locals[*id].inout {
                    raw_local_name(&f.locals, *id)
                } else {
                    format!("&{}", local_name(&f.locals, *id))
                }
            }
            HExprKind::Push { local, value } => {
                let name = local_name(&f.locals, *local);
                let at = pos(e.at);
                match f.locals[*local].ty {
                    Ty::String => {
                        let v = self.borrowed(value, f);
                        let view = if value.ty == Ty::String { format!("yv_string_view(&{v})") } else { v };
                        self.line(&format!("yv_string_push(&{name}, {view}, {at});"));
                    }
                    Ty::Vec(vid) => {
                        let et = vec_elem(vid).c_name();
                        let v = self.owned(value, f);
                        self.line(&format!("*({et} *)yv_vec_push_slot(&{name}, (int64_t)sizeof({et}), {at}) = {v};"));
                    }
                    _ => unreachable!(),
                }
                String::new()
            }
            HExprKind::Neg(inner) => {
                let v = self.expr(inner, f);
                let Ty::Int(t) = e.ty else { unreachable!() };
                self.bind(e.ty, &format!("yv_neg_{}({v}, {})", t.suffix(), pos(e.at)))
            }
            HExprKind::Not(inner) => {
                let v = self.expr(inner, f);
                format!("(!{v})")
            }
            HExprKind::Convert { to, checked, expr } => {
                let v = self.expr(expr, f);
                let Ty::Int(from) = expr.ty else { unreachable!() };
                let text = if *checked {
                    format!("yv_conv_{}_{}({v}, {})", from.suffix(), to.suffix(), pos(e.at))
                } else {
                    format!("(({})(uint64_t)({v}))", to.c_name())
                };
                self.bind(e.ty, &text)
            }
            HExprKind::Binary { op: op @ (BinOp::And | BinOp::Or), lhs, rhs } => {
                let t = self.fresh();
                let l = self.expr(lhs, f);
                self.line(&format!("bool {t} = {l};"));
                let guard = if *op == BinOp::And { format!("if ({t}) {{") } else { format!("if (!{t}) {{") };
                self.line(&guard);
                self.indent += 1;
                // Temporaries of the right operand live in this nested C block, so they are
                // dropped here rather than at the end of the statement.
                let mark = self.temps.len();
                let r = self.expr(rhs, f);
                self.line(&format!("{t} = {r};"));
                let inner = self.temps.split_off(mark);
                for (name, ty) in inner.iter().rev() {
                    self.line(&format!("{}(&{name});", drop_fn(*ty)));
                }
                self.indent -= 1;
                self.line("}");
                t
            }
            HExprKind::Binary { op, lhs, rhs } => {
                let l = if lhs.ty.is_copy() { self.expr(lhs, f) } else { self.borrowed(lhs, f) };
                let r = if rhs.ty.is_copy() { self.expr(rhs, f) } else { self.borrowed(rhs, f) };
                self.binary(*op, e, lhs.ty, rhs.ty, &l, &r)
            }
        }
    }

    /// The value of `e` where it is handed over: a new variable, an assignment, a `sink`
    /// argument, a return value or a vector element. Moving a local empties it (see `Move`).
    fn owned(&mut self, e: &HExpr, f: &HFn) -> String {
        self.expr(e, f)
    }

    /// The value of `e` where it is only borrowed. An owned temporary (a call result, a
    /// clone, a literal) is dropped at the end of the statement.
    fn borrowed(&mut self, e: &HExpr, f: &HFn) -> String {
        let v = self.expr(e, f);
        // Only values this statement created and owns are dropped; a value read through a
        // reference or a parameter belongs to someone else.
        let fresh = matches!(
            e.kind,
            HExprKind::Call { .. }
                | HExprKind::VecLit(_)
                | HExprKind::Move(_)
                | HExprKind::Method {
                    method: Builtin::StrToString | Builtin::StringClone | Builtin::VecClone | Builtin::Fields | Builtin::Lines,
                    ..
                }
        );
        if fresh && !e.ty.is_copy() {
            self.temps.push((v.clone(), e.ty));
        }
        v
    }

    /// A mutable temporary, used for owned values so that they can later be dropped.
    fn bind_mut(&mut self, ty: Ty, value: &str) -> String {
        let t = self.fresh();
        self.line(&format!("{} {t} = {value};", ty.c_name()));
        t
    }

    fn bind(&mut self, ty: Ty, value: &str) -> String {
        let t = self.fresh();
        // `&T` is already `const T *`; a second `const` would only trigger warnings.
        let q = if matches!(ty, Ty::Ref(_)) { "" } else { "const " };
        self.line(&format!("{q}{} {t} = {value};", ty.c_name()));
        t
    }

    fn binary(&mut self, op: BinOp, e: &HExpr, lty: Ty, rty: Ty, l: &str, r: &str) -> String {
        let cmp = match op {
            BinOp::Eq => Some("=="),
            BinOp::Ne => Some("!="),
            BinOp::Lt => Some("<"),
            BinOp::Le => Some("<="),
            BinOp::Gt => Some(">"),
            BinOp::Ge => Some(">="),
            _ => None,
        };
        if let Some(c) = cmp {
            if matches!(lty, Ty::Str | Ty::String) {
                let (lv, rv) = if lty == Ty::String {
                    (format!("yv_string_view(&{l})"), format!("yv_string_view(&{r})"))
                } else {
                    (l.to_string(), r.to_string())
                };
                return match op {
                    BinOp::Eq => format!("(yv_str_eq({lv}, {rv}))"),
                    BinOp::Ne => format!("(!yv_str_eq({lv}, {rv}))"),
                    _ => format!("(yv_str_cmp({lv}, {rv}) {c} 0)"),
                };
            }
            return format!("({l} {c} {r})");
        }
        let Ty::Int(t) = e.ty else { unreachable!() };
        let s = t.suffix();
        let at = pos(e.at);
        let text = match op {
            BinOp::Add => format!("yv_add_{s}({l}, {r}, {at})"),
            BinOp::Sub => format!("yv_sub_{s}({l}, {r}, {at})"),
            BinOp::Mul => format!("yv_mul_{s}({l}, {r}, {at})"),
            BinOp::Div => format!("yv_div_{s}({l}, {r}, {at})"),
            BinOp::Rem => format!("yv_rem_{s}({l}, {r}, {at})"),
            BinOp::AddWrap => format!("yv_addw_{s}({l}, {r})"),
            BinOp::SubWrap => format!("yv_subw_{s}({l}, {r})"),
            BinOp::MulWrap => format!("yv_mulw_{s}({l}, {r})"),
            BinOp::BitAnd => format!("(({}) ({l} & {r}))", t.c_name()),
            BinOp::BitOr => format!("(({}) ({l} | {r}))", t.c_name()),
            BinOp::BitXor => format!("(({}) ({l} ^ {r}))", t.c_name()),
            BinOp::Shl | BinOp::Shr => {
                let Ty::Int(rt) = rty else { unreachable!() };
                let dir = if op == BinOp::Shl { "shl" } else { "shr" };
                let amount = if rt.signed() { format!("(int64_t){r}") } else { format!("(int64_t)(uint64_t){r}") };
                let amount = if rt == IntTy::U64 {
                    format!("yv_shift_amount_u64({r}, {at})")
                } else {
                    amount
                };
                format!("yv_{dir}_{s}({l}, {amount}, {at})")
            }
            _ => unreachable!(),
        };
        self.bind(e.ty, &text)
    }
}
